export const GENERATOR = "oma explain render";

export type StyleLevel = "off" | "warn" | "strict";
export type ColorMode = "auto" | "light" | "dark";

export interface RenderOptions {
  theme?: string;
  mode?: string;
  style?: string;
  lang?: string;
  /** Relative href of an archify sidecar to link from the page. */
  sidecarHref?: string;
  /** Shown in the footer; defaults to today. */
  date?: string;
}

export interface PanelDiagram {
  panelId: string;
  /** The panel carries the `archify` attribute. */
  preferred: boolean;
  title: string;
  model: DiagramModel;
}

export interface RenderResult {
  html: string;
  draft: Draft;
  lang: DraftLanguage;
  theme: ThemeName;
  style: StyleLevel;
  warnings: LintWarning[];
  /** Flow and sequence diagrams in the page, for the archify sidecar. */
  diagrams: PanelDiagram[];
}

interface Strings {
  right: string;
  wrong: string;
  theme: string;
  print: string;
  score: string;
  generated: string;
  interactive: string;
}

