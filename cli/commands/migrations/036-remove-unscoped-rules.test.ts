import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { readRules } from "../../platform/rules.js";
import { removeUnscopedRules } from "./036-remove-unscoped-rules.js";

const repoRoot = fileURLToPath(new URL("../../..", import.meta.url));
const tempRoots: string[] = [];

afterEach(() => {
  for (const root of tempRoots) rmSync(root, { recursive: true, force: true });
  tempRoots.length = 0;
});

function tempDir(): string {
  const dir = mkdtempSync(join(tmpdir(), "oma-migrate-036-"));
  tempRoots.push(dir);
  return dir;
}

function put(root: string, path: string, body: string): string {
  const file = join(root, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, body);
  return file;
}

const SHIPPED_BACKEND =
  "---\ndescription: Backend API coding standards with clean architecture (Router/Service/Repository pattern)\nglobs:\nalwaysApply: false\n---\n\n# Backend\n";
const GENERATED_CLAUDE =
  "---\ndescription: Quality assurance standards for security (OWASP), performance, accessibility (WCAG), and code quality reviews\n---\n\n# Quality\n";
const GENERATED_CURSOR =
  '---\ndescription: "x"\nglobs: \nalwaysApply: false\n---\n\n<!-- Generated by oh-my-agent. Source: .agents/rules/commit.md -->\n\n# Commit\n';

describe("removeUnscopedRules (036)", () => {
  it("removes shipped rules and their vendor copies, then is a no-op", () => {
    const project = tempDir();
    const home = tempDir();
    const source = put(project, ".agents/rules/backend.md", SHIPPED_BACKEND);
    const claude = put(project, ".claude/rules/quality.md", GENERATED_CLAUDE);
    const cursor = put(project, ".cursor/rules/commit.mdc", GENERATED_CURSOR);
    const globalClaude = put(home, ".claude/rules/backend.md", SHIPPED_BACKEND);

    expect(
      removeUnscopedRules(project, { vendors: null }, home).sort(),
    ).toEqual([
      ".agents/rules/backend.md (removed unscoped rule)",
      ".claude/rules/quality.md (removed unscoped rule)",
      ".cursor/rules/commit.mdc (removed unscoped rule)",
      "~/.claude/rules/backend.md (removed unscoped rule)",
    ]);
    for (const file of [source, claude, cursor, globalClaude]) {
      expect(existsSync(file)).toBe(false);
    }
    expect(removeUnscopedRules(project, { vendors: null }, home)).toEqual([]);
  });

  it("leaves a project rule that only reuses a shipped name", () => {
    const project = tempDir();
    const own = put(
      project,
      ".agents/rules/backend.md",
      "---\ndescription: Our service conventions\nglobs:\nalwaysApply: false\n---\n\n# Ours\n",
    );
    const handWritten = put(
      project,
      ".cursor/rules/commit.mdc",
      "---\ndescription: team commit rules\n---\n\n# Ours\n",
    );

    expect(removeUnscopedRules(project, { vendors: null }, tempDir())).toEqual(
      [],
    );
    expect(existsSync(own)).toBe(true);
    expect(existsSync(handWritten)).toBe(true);
  });

  it("leaves scoped rules and other names alone", () => {
    const project = tempDir();
    const scoped = put(
      project,
      ".agents/rules/database.md",
      '---\ndescription: Database schema design\nglobs: "**/*.sql"\nalwaysApply: false\n---\n',
    );

    expect(removeUnscopedRules(project, { vendors: null }, tempDir())).toEqual(
      [],
    );
    expect(existsSync(scoped)).toBe(true);
  });

  it("does not touch a vendor the run may not write to", () => {
    const project = tempDir();
    const claude = put(project, ".claude/rules/quality.md", GENERATED_CLAUDE);

    expect(removeUnscopedRules(project, { vendors: [] }, tempDir())).toEqual(
      [],
    );
    expect(existsSync(claude)).toBe(true);
  });

  // Regression: a rule with neither `globs` nor `alwaysApply` has no host that
  // loads it on a path match, and Claude Code would load it everywhere.
  it("ships no rule without a load scope", () => {
    const unscoped = readRules(repoRoot)
      .filter((rule) => !rule.globs && !rule.alwaysApply)
      .map((rule) => rule.name);

    expect(unscoped).toEqual([]);
    expect(
      readdirSync(join(repoRoot, ".agents", "rules")).length,
    ).toBeGreaterThan(0);
  });
});
