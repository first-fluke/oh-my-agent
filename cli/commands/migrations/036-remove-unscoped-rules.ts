/**
 * Migration 036: Remove the rules that had no load scope.
 *
 * Seven shipped rules (`backend`, `commit`, `debug`, `design`, `dev-workflow`,
 * `market`, `quality`) carried neither `globs` nor `alwaysApply`. Their content
 * lives in the skill that owns the domain, so they stopped shipping. `oma
 * update` overwrites shipped rules but never prunes one, and vendor copies are
 * regenerated only for rules that still exist, so both are removed here. The
 * Claude copy matters most: Claude Code loads a rule without `paths` into
 * every session.
 *
 * Only shipped files are removed. A project rule that reuses one of the names
 * is recognized by a different `description` and is left alone.
 */
import { existsSync, readFileSync, rmSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import type { CliVendor } from "../../types/index.js";
import type { Migration } from "./index.js";
import { allowsVendor, type MigrationContext } from "./vendor-scope.js";

/** Rule name → the opening of every `description` it has shipped with. */
const SHIPPED_DESCRIPTIONS: Record<string, string> = {
  backend: "Backend API coding standards with clean architecture",
  commit: "Conventional Commits specification and git commit workflow rules",
  debug: "Bug diagnosis and fixing standards",
  design: "Design system, typography, color, accessibility",
  "dev-workflow": "Monorepo developer workflow standards",
  market: "Market research standards - trap detection",
  quality: "Quality assurance standards for security (OWASP)",
};

const CURSOR_GENERATED =
  "<!-- Generated by oh-my-agent. Source: .agents/rules/";

function isShipped(path: string, name: string): boolean {
  const shipped = SHIPPED_DESCRIPTIONS[name];
  if (!shipped) return false;
  const match = /^description:\s*["']?(.*)$/m.exec(readFileSync(path, "utf-8"));
  return match?.[1]?.startsWith(shipped) === true;
}

function removeIf(
  path: string,
  label: string,
  matches: (path: string) => boolean,
  actions: string[],
): void {
  if (!existsSync(path)) return;
  try {
    if (!matches(path)) return;
    rmSync(path, { force: true });
    actions.push(`${label} (removed unscoped rule)`);
  } catch {
    // Best-effort: leave an unreadable or protected file untouched.
  }
}

export function removeUnscopedRules(
  cwd: string,
  ctx?: MigrationContext,
  home: string = homedir(),
): string[] {
  const actions: string[] = [];
  const vendorRoots: Array<{ root: string; label: string }> = [
    { root: cwd, label: "" },
    { root: home, label: "~/" },
  ];

  for (const name of Object.keys(SHIPPED_DESCRIPTIONS)) {
    removeIf(
      join(cwd, ".agents", "rules", `${name}.md`),
      `.agents/rules/${name}.md`,
      (path) => isShipped(path, name),
      actions,
    );

    const copies: Array<{
      vendor: CliVendor;
      dir: string[];
      file: string;
      matches: (path: string) => boolean;
    }> = [
      {
        vendor: "claude",
        dir: [".claude", "rules"],
        file: `${name}.md`,
        matches: (path) => isShipped(path, name),
      },
      {
        vendor: "cursor",
        dir: [".cursor", "rules"],
        file: `${name}.mdc`,
        matches: (path) =>
          readFileSync(path, "utf-8").includes(
            `${CURSOR_GENERATED}${name}.md -->`,
          ),
      },
    ];
    for (const copy of copies) {
      if (!allowsVendor(ctx, copy.vendor)) continue;
      for (const { root, label } of vendorRoots) {
        removeIf(
          join(root, ...copy.dir, copy.file),
          `${label}${copy.dir.join("/")}/${copy.file}`,
          copy.matches,
          actions,
        );
      }
    }
  }
  return actions;
}

export const migrateRemoveUnscopedRules: Migration = {
  name: "036-remove-unscoped-rules",
  up(cwd: string, ctx?: MigrationContext): string[] {
    return removeUnscopedRules(cwd, ctx);
  },
};
