#!/usr/bin/env node
// Writes the published bin entry `bin/cli.js`: a tiny loader that turns on
// Node's on-disk compile cache, then imports the real bundle `bin/cli-main.js`.
// Every vendor hook event spawns `oma hook run`, and re-parsing the
// multi-megabyte bundle dominated that latency. With a warm cache V8 reuses
// the compiled code instead. The cache only covers modules loaded after it is
// enabled, which is why the bundle sits behind this separate loader.
//
// Usage: node scripts/write-bin-entry.mjs [outDir]   (default: cli/bin)

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const BUNDLE_FILE = "cli-main.js";

export const BIN_ENTRY_SOURCE = `#!/usr/bin/env node
// Generated by cli/scripts/write-bin-entry.mjs; do not edit.
import module from "node:module";

try {
  // Node >= 22.1, a no-op elsewhere. NODE_DISABLE_COMPILE_CACHE=1 opts out.
  module.enableCompileCache?.();
} catch {
  // The cache only speeds up startup; never fail the CLI over it.
}

await import("./${BUNDLE_FILE}");
`;

export function writeBinEntry(
  outDir = fileURLToPath(new URL("../bin", import.meta.url)),
) {
  mkdirSync(outDir, { recursive: true });
  const entry = join(outDir, "cli.js");
  writeFileSync(entry, BIN_ENTRY_SOURCE);
  chmodSync(entry, 0o755);
  return entry;
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const outDir = process.argv[2] ? resolve(process.argv[2]) : undefined;
  console.log(`bin entry written: ${writeBinEntry(outDir)}`);
}
